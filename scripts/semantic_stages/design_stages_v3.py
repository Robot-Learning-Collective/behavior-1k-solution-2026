"""Semantic stages v3 (2026-09-17 stage audit): regroup the v2.2 medoid atoms per task with the reviewed rules
and write the v3 assets. The v2.2 machinery (canonical skill sequence = medoid_g2, consistent cuts, unordered / class
blocks, per-episode split positions) is reused unchanged from design_stages.py; v3 only changes HOW the atoms are grouped
into stages. Every v3 stage is a contiguous range of medoid atoms [a, b), optionally one of P equal-time parts of it.

Rules (user review 2026-09-17, see eval_logs/claude_experiments/stage_audit_2026-09-17/ and EXPERIMENTS.md):
  R1 a miss-able grasp (pick up, hand over, open door/lid/drawer, pull tray, hold) and a full-close skill (press, switch,
     toggle, ignite) never share a stage (the auto-open rule must be able to tell a missed grasp from a press);
  R2 an OPEN and a TURN ON of the same appliance start from the same state: they need >= 2 stages between them unless the
     robot holds an object in one of them - a transfer between them is split into pick / place halves;
  R3 a skill sequence repeated back to back is ONE stage (repeats detected at the atom level, period <= 12); the same step
     twice in a row merges forward;
  R4 pick-and-place transfers are grouped by object; "move to X + open X" is one stage; a transfer whose destination is a
     real manipulation (attach, hold, insert, hang, pour, wipe, ...) is split at the carry move (R4b);
  R5 unordered / class blocks stay whole and are cut into <= 5 equal-time parts of ~150 s;
  R6 approach-only units join the action at their target; other short units merge back only when not final, the previous
     unit is < 120 s and R1-safe; a distinct final action (last placement / door close) keeps its own stage; ordered
     stages over 300 s are time-split.
Carrying = only objects that are placed later in the task (a held tool / container does not make the next move a carry).

Inputs : outputs/semantic_stages/v2/{details.json, structure.json, termination.csv, tasks.csv, episode_stage_frames.csv}
         (regenerated by scripts/prepare_semantic_stages.sh) + the skill annotations of all 100 tasks
         ($B1K_DEMOS_ROOT/annotations, meta/).
Outputs: $STAGE_OUT_V3 (default outputs/semantic_stages/v3)/
         stages.csv, tasks.csv          frozen v3 spec (versioned; TASK_NUM_STAGES_2026_SEM_V3 = tasks.csv n_stages)
         stage_defs.json                per task: skills, medoid range, part, tags, duration stats (versioned)
         episode_stage_frames.csv       per-frame training labels (episode_index, stage, start, end), git-ignored
         v2_to_v3_overlap.json          per task: W[new stage][old stage] = share of new-stage training frames that carried
                                        old stage i (input of scripts/surgery_stage_layout.py), versioned
         STAGES.md                      human-readable listing of all 100 tasks

  B1K_DEMOS_ROOT=data/2026-challenge-demos uv run --no-sync python scripts/semantic_stages/design_stages_v3.py
  # optional self-check against the audit's proposal: PROPOSAL_JSON=<...>/proposal.json
"""
