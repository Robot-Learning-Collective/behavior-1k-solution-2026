# skill classes (measured on all 20k demos, gripper_by_skill.json in the audit dir)
FIXTURE = {"open door", "close door", "open lid", "close lid", "turn on switch", "turn off switch", "press", "toggle on", "toggle off", "ignite"}
MISSABLE = {"pick up from", "pick up", "hand over", "open door", "open lid", "open drawer", "pull tray", "hold"}   # close ON something; a miss = closed on nothing
AIR = {"press", "turn on switch", "turn off switch", "toggle on", "toggle off", "ignite"}                            # close settles fully (< 1 mm)
OPENS = {"open door", "open lid"}; ONS = {"turn on switch", "toggle on"}
GRASP = {"pick up from", "pick up", "hand over"}
PLACE = {"place on", "place in", "place under", "place on next to", "place in next to", "place next to", "pour", "attach"}
PLAIN = {"place on", "place in", "place under", "place on next to", "place in next to", "place next to", "close door", "close lid", "move to"}
MAXS, TARGET, MINS = 300.0, 150.0, 25.0


def alike(ka, kb): return (ka in OPENS and kb in ONS) or (ka in ONS and kb in OPENS)
def kind(sk): m = re.match(r"([a-z ]+?)\(", sk); return m.group(1) if m else sk
def objs(sk): m = re.search(r"\((.*)\)", sk); return [o for o in m.group(1).split(",") if o] if m else []
def has(unit, S): return any(kind(s) in S for s in unit["skills"])


def skill_durations(eps):
    """mean duration (s) per skill string and per skill kind over the task's annotated segments (cut at completion)."""
    d = collections.defaultdict(list); k = collections.defaultdict(list)
    for e in eps:
        for sg in e["segs"]:
            t = (sg["s1"] - sg["s0"]) / D.FPS; d[sg["g2"]].append(t); k[kind(sg["g2"])].append(t)
    return {s: float(np.mean(v)) for s, v in d.items()}, {s: float(np.mean(v)) for s, v in k.items()}


def propose(ti, med, S, sdur, kdur, len_s):
    """v3 units for one task (verbatim port of the audit's proposal.py, 2026-09-17 final). Returns (units, warnings);
    each unit = dict(skills, dur, tags, block, rep, parts)."""
    n = len(med)
    def dur(sk):
        if sk in sdur: return sdur[sk]
        return kdur.get(kind(sk), 10.0)
    blocks = {}
    for r in S.get("unordered_regions", []):
        a, b = r["block"]
        for x in range(a, b): blocks[x] = (a, b, "unordered" if r["m"] > 1 else "group", r["mean_s"])
    for r in S.get("class_regions", []):
        a, b = r["block"]; ms = sum(dur(med[x]) for x in range(a, b))
        for x in range(a, b): blocks[x] = (a, b, "class", ms)
    # R3 at the atom level: the same sequence of (non-move) skills repeated >= 2 times back to back is one block
    core = [i for i in range(n) if kind(med[i]) != "move to" and i not in blocks]
    csk = [med[i] for i in core]; i = 0
    while i < len(core):
        best = None
        for pp in range(2, min(12, (len(core) - i) // 2) + 1):
            r = 1
            while i + (r + 1) * pp <= len(core) and csk[i + r * pp:i + (r + 1) * pp] == csk[i:i + pp]: r += 1
            if r >= 2 and (best is None or r * pp > best[0] * best[1]): best = (r, pp)
        if best:
            r, pp = best; a = core[i]; b = core[i + r * pp - 1] + 1
            if a > 0 and kind(med[a - 1]) == "move to" and (a - 1) not in blocks: a -= 1      # include the approach move of the first repeat
            if not any(x in blocks for x in range(a, b)):
                ms = sum(dur(med[x]) for x in range(a, b))
                for x in range(a, b): blocks[x] = (a, b, "repeat", ms)
            i += r * pp
        else: i += 1
    units = []
    def new(sk, tag=None): units.append(dict(skills=[sk], tags=set([tag]) if tag else set(), block=None, closed=False))
    def cur(): return units[-1] if units and units[-1]["block"] is None and not units[-1]["closed"] else None
    # objects that are placed somewhere later in the task are "transferred"; an object picked up and never placed (trash can,
    # basket carried throughout, broom, sprayer, lighter) is a tool/container: holding it does not make the next move a carry move
    transferred = {objs(s)[0] for s in med if kind(s) in PLACE and objs(s)}
    def carrying(u):
        g = [objs(s)[0] for s in u["skills"] if kind(s) in GRASP | {"push to"} and objs(s) and objs(s)[0] in transferred]
        p = [objs(s)[0] for s in u["skills"] if kind(s) in PLACE and objs(s)]
        return [x for x in g if x not in p]
    i = 0
    while i < n:
        sk = med[i]; k = kind(sk); o = objs(sk); nxt = med[i + 1] if i + 1 < n else None
        if i in blocks:
            a, b, bk, ms = blocks[i]
            if bk == "group":   # a small unordered group: one unit, but mergeable like an ordered unit
                units.append(dict(skills=med[a:b], tags={"small unordered group kept together"}, block=None, closed=True, fixed_dur=ms))
            elif bk == "repeat":
                units.append(dict(skills=med[a:b], tags={"R3: the same skill sequence repeated back to back is one stage"}, block=None, closed=True, fixed_dur=ms, rep=2))
            else: units.append(dict(skills=med[a:b], tags={f"{bk} block kept whole (order unreliable)"}, block=(a, b, bk, ms), closed=True))
            i = b; continue
        u = cur()
        if units and sk == units[-1]["skills"][-1] and units[-1]["block"] is None: units[-1]["skills"].append(sk); i += 1; continue   # consecutive duplicate = same operation continued (redo / second door leaf)
        if u is None: new(sk)
        elif k == "move to":
            if carrying(u): u["skills"].append(sk)   # split later only if R2 needs it
            else: new(sk)
        elif k in ("open door", "open lid"):
            last = u["skills"][-1]
            if kind(last) == "move to" and objs(last)[:1] == o[:1] and len(u["skills"]) == 1: u["skills"].append(sk); u["tags"].add("move to + open = one stage"); u["closed"] = True
            elif has(u, GRASP | PLACE | AIR): new(sk, "R1: door/lid grasp separated from the closed-on-air skill" if has(u, AIR) else None)
            else: u["skills"].append(sk); u["closed"] = True
        elif k in GRASP | {"push to"}:
            if has(u, AIR) and k in MISSABLE: new(sk, "R1: grasp separated from the closed-on-air skill")
            elif [x for x in u["skills"] if kind(x) in PLACE] and o and o[0] not in carrying(u): new(sk, "R4: next object = next transfer unit")
            else: u["skills"].append(sk)
        elif k in PLACE: u["skills"].append(sk)
        elif k in ("close door", "close lid"):
            if nxt and kind(nxt) in AIR and objs(nxt)[:1] == o[:1]: new(sk, "R2/R1: close + switch as its own finishing stage")
            elif carrying(u): new(sk, "R2: close after the grasp starts the carry stage")
            else: u["skills"].append(sk)
        elif k in AIR:
            if has(u, MISSABLE): new(sk, "R1: closed-on-air skill separated from the grasp")
            else: u["skills"].append(sk)
        else: u["skills"].append(sk)
        i += 1
    for u in units: u["dur"] = u["block"][3] if u["block"] else (u["fixed_dur"] if u.get("fixed_dur") else sum(dur(s) for s in u["skills"]))
    # R3: merge repeated patterns (period k<=4, >=2 repeats) of non-block units
    def merge_repeats(units):
        def usig(u):
            if u["block"] is not None: return ("BLOCK", id(u))
            r = u.get("rep", 1); c = collections.Counter((kind(s), tuple(objs(s))) for s in u["skills"])
            return tuple(sorted((k, v // r if v % r == 0 else v) for k, v in c.items()))   # per-repeat signature
        sigs = [usig(u) for u in units]; out = []; i = 0
        while i < len(units):
            best = None
            for k in range(1, 5):
                r = 1
                while i + (r + 1) * k <= len(units) and sigs[i + r * k:i + (r + 1) * k] == sigs[i:i + k] and all(units[x]["block"] is None for x in range(i, i + k)): r += 1
                if r >= 2 and (best is None or r * k > best[0] * best[1]): best = (r, k)
            if best:
                r, k = best; span = units[i:i + r * k]
                reps = sum(u.get("rep", 1) for u in span) if k == 1 else r
                m = dict(skills=sum([u["skills"] for u in span], []), tags=set().union(*[u["tags"] for u in span]) | {f"R3: {k}-unit pattern repeated {reps}x merged"}, block=None, closed=True, dur=sum(u["dur"] for u in span), rep=reps)
                out.append(m); i += r * k
            else: out.append(units[i]); i += 1
        return out
    units = merge_repeats(units)
    # R3b: the same step repeated right before a unit that contains it (e.g. pick up the second tupperware): merge forward
    out = []; i = 0
    while i < len(units):
        u = units[i]
        if u["block"] is None and i + 1 < len(units) and u["dur"] <= 45 and u.get("rep", 1) == 1:
            nx = units[i + 1]; cu = collections.Counter(x for x in u["skills"] if kind(x) != "move to"); cn = collections.Counter(x for x in nx["skills"] if kind(x) != "move to")
            if cu and all(cn[k] >= v for k, v in cu.items()):
                nx["skills"] = u["skills"] + nx["skills"]; nx["dur"] += u["dur"]; nx["tags"] |= u["tags"] | {"R3: same step twice in a row merged"}
                if nx["block"] is not None: nx["block"] = (nx["block"][0], nx["block"][1], nx["block"][2], nx["dur"])
                i += 1; continue
        out.append(u); i += 1
    units = out
    # R4b: a transfer whose destination half is a real manipulation (attach, hold, insert, hang, pour, wipe, chop, ...) rather than
    #      a plain placement is split at the carry move: [move to + pick up] then [move to target + the manipulation]
    out = []
    for u in units:
        if u["block"] is None and u.get("rep", 1) == 1:
            for j in range(1, len(u["skills"])):
                if kind(u["skills"][j]) == "move to" and carrying(dict(skills=u["skills"][:j])):
                    tail = [kind(x) for x in u["skills"][j:]]
                    if any(k not in PLAIN and k not in GRASP for k in tail):
                        u1 = dict(u, skills=u["skills"][:j], tags=set(u["tags"]) | {"R4: pick-up and the manipulation at the target are separate stages"}); u2 = dict(u, skills=u["skills"][j:], tags=set(u1["tags"]))
                        u1["dur"] = sum(dur(x) for x in u1["skills"]); u2["dur"] = sum(dur(x) for x in u2["skills"])
                        out += [u1, u2]; break
            else: out.append(u)
        else: out.append(u)
    units = out
    # R2: look-alike fixture ops need >=2 units between; split a transfer unit between them at its carry move
    def holding_before(units, ui, si):
        carried = []
        for x, u in enumerate(units):
            for j, s in enumerate(u["skills"]):
                if x == ui and j == si: return carried
                k = kind(s); o = objs(s)
                if k in GRASP | {"push to"} and o: carried.append(o[0])
                elif k in PLACE and o and o[0] in carried: carried.remove(o[0])
        return carried
    def fixture_list(units): return [(ui, kind(s), objs(s)[0], bool(holding_before(units, ui, j))) for ui, u in enumerate(units) for j, s in enumerate(u["skills"]) if kind(s) in OPENS | ONS and objs(s) and u["block"] is None]
    changed = True; guard = 0
    while changed and guard < 10:
        changed = False; guard += 1; fx = fixture_list(units)
        for a in range(len(fx)):
            for b in range(a + 1, len(fx)):
                ua, ka, oa, ha = fx[a]; ub, kb, ob, hb = fx[b]
                if oa != ob or not alike(ka, kb) or ha or hb or ub == ua or ub - ua > 2: continue
                for ui in range(ua + 1, ub):
                    u = units[ui]
                    if u["block"] is not None or u.get("rep", 1) > 1: continue
                    for j in range(1, len(u["skills"])):
                        if kind(u["skills"][j]) == "move to" and carrying(dict(skills=u["skills"][:j])):
                            u1 = dict(u, skills=u["skills"][:j], tags=set(u["tags"]) | {"R2: transfer split into pick / place halves to space look-alike fixture ops"}); u2 = dict(u, skills=u["skills"][j:], tags=set(u1["tags"]))
                            u1["dur"] = sum(dur(s) for s in u1["skills"]); u2["dur"] = sum(dur(s) for s in u2["skills"])
                            units[ui:ui + 1] = [u1, u2]; changed = True; break
                    if changed: break
                if changed: break
            if changed: break
    # R6a: approach-only units join the next unit (move to X + the action at X)
    def r1_ok(x, y): return not ((has(x, AIR) and has(y, MISSABLE)) or (has(x, MISSABLE) and has(y, AIR)))
    mins = min(MINS, 0.15 * len_s)
    def landmark(u): return has(u, FIXTURE | AIR)
    def approach_only(u): return u["block"] is None and all(kind(s) == "move to" for s in u["skills"])
    out = []; i = 0
    while i < len(units):
        u = units[i]
        if approach_only(u) and i + 1 < len(units) and units[i + 1]["block"] is None:
            nx = units[i + 1]; nx["skills"] = u["skills"] + nx["skills"]; nx["dur"] += u["dur"]; nx["tags"] |= u["tags"] | {"R6: approach joined to the action at its target"}; i += 1; continue
        out.append(u); i += 1
    units = out
    # R6b: other short units merge into the previous unit only when they are not the final stage, the previous unit is not
    #      already long (>120 s) and R1 is safe; a short specific action (final place, close door) stays its own stage
    out = []
    for j, u in enumerate(units):
        last = (j == len(units) - 1)
        specific_final = last and all(kind(x) in PLACE | {"close door", "close lid"} for x in u["skills"])
        tiny = u["dur"] < 12
        if u["block"] is None and u["dur"] < mins and not specific_final and out and out[-1]["block"] is None and (out[-1]["dur"] < 120 or tiny) and r1_ok(u, out[-1]) and not landmark(u) and not landmark(out[-1]) and not u.get("rep", 1) > 1:
            out[-1]["skills"] += u["skills"]; out[-1]["dur"] += u["dur"]; out[-1]["tags"] |= u["tags"] | {"R6: short unit merged"}; continue
        out.append(u)
    units = out
    units = merge_repeats(units)   # a lone approach unit may have split a run of identical units before R6a joined it
    # R6c: the task's final specific action (a placement or a door close ending a long last unit) stays its own stage
    if units and units[-1]["block"] is None and len(units[-1]["skills"]) > 1 and units[-1]["dur"] > 120:
        lastu = units[-1]; lk = kind(lastu["skills"][-1])
        if lk in PLACE | {"close door", "close lid"} and dur(lastu["skills"][-1]) >= 15 and lastu["skills"].count(lastu["skills"][-1]) == 1 and lastu.get("rep", 1) == 1:
            fin = dict(skills=[lastu["skills"][-1]], tags={"R6: specific final action kept as its own stage"}, block=None, closed=True, dur=dur(lastu["skills"][-1]), rep=1)
            lastu["skills"] = lastu["skills"][:-1]; lastu["dur"] -= fin["dur"]; units.append(fin)
    warn = []; fx = fixture_list(units)
    for a in range(len(fx)):
        for b in range(a + 1, len(fx)):
            if fx[a][2] == fx[b][2] and alike(fx[a][1], fx[b][1]) and not fx[a][3] and not fx[b][3] and 1 <= fx[b][0] - fx[a][0] <= 1:
                warn.append(f"R2 unresolved: '{fx[a][1]}' and '{fx[b][1]}' on {fx[a][2]} start from the same state in adjacent stages {fx[a][0]},{fx[b][0]}")
    for u in units:
        if u["block"] is None: u["parts"] = max(1, math.ceil(u["dur"] / MAXS)) if u["dur"] <= MAXS else math.ceil(u["dur"] / TARGET)
        else: u["parts"] = max(1, min(5, math.ceil(u["dur"] / TARGET)))
        if u["block"] is None and u["parts"] > 1: u["tags"].add(f"R6: {u['dur']:.0f} s split into {u['parts']} time parts")
        if u["block"] is not None: u["tags"].add(f"R5: {u['dur']:.0f} s block -> {u['parts']} time part(s) of ~{u['dur'] / u['parts']:.0f} s")
        u["tags"] = sorted(u["tags"]); u["rep"] = u.get("rep", 1); u["block"] = u["block"][2] if u["block"] else None
    return units, warn


def frame_labels(ti, eps, med, units):
    """Per-episode frame runs for the v3 stages. Stage boundaries are the v2.2 per-episode split positions of the
    medoid cuts (cut_split, monotone); a stage empty in an episode takes zero frames; time parts are equal slices of the
    unit's span in each episode (like the v2.2 progress parts)."""
    K = len(med); seqs = [[s["g2"] for s in e["segs"]] for e in eps]
    splits = np.zeros((len(eps), K + 1), int); splits[:, K] = [len(s) for s in seqs]
    for k in range(1, K):
        A, B = med[:k], med[k:]
        for ei, seq in enumerate(seqs):
            s, _ = D.cut_split(seq, A, B); splits[ei, k] = max(s, splits[ei, k - 1])
    stages = []  # (a, b, p, P)
    a = 0
    for u in units:
        b = a + len(u["skills"])
        for p in range(u["parts"]): stages.append((a, b, p, u["parts"]))
        a = b
    assert a == K, (ti, a, K)
    labels = []; empty = np.zeros(len(stages), int)
    for ei, e in enumerate(eps):
        segs = e["segs"]; bounds = []
        for (a, b, p, P) in stages:
            i0, i1 = splits[ei, a], splits[ei, b]
            if i1 <= i0: bounds.append(None); continue
            f0, f1 = segs[i0]["s0"], segs[i1 - 1]["s1"]
            bounds.append(int(f0 + (f1 - f0) * p / P))
        nxt = e["comp"]
        for i in range(len(bounds) - 1, -1, -1):
            if bounds[i] is None: bounds[i] = nxt
            else: nxt = bounds[i]
        bounds[0] = 0
        for i in range(1, len(bounds)): bounds[i] = max(bounds[i], bounds[i - 1])
        frame = np.zeros(max(e["comp"], 1), int)
        for i in range(len(stages)):
            s0 = bounds[i]; s1 = bounds[i + 1] if i + 1 < len(stages) else e["comp"]; frame[s0:s1] = i
            if s1 <= s0: empty[i] += 1
        ch = np.concatenate([[0], np.where(np.diff(frame) != 0)[0] + 1, [len(frame)]])
        for r0, r1 in zip(ch[:-1], ch[1:]): labels.append((e["ep"], int(frame[r0]), int(r0), int(r1)))
    return stages, labels


def overlap_matrix(ti, lab_new, lab_old, n_new, n_old):
    """W[j, i] = share of the training frames of new stage j that carry old stage i (all episodes of the task)."""
    W = np.zeros((n_new, n_old))
    old = {e: g for e, g in lab_old.groupby("episode_index")}
    for e, g in lab_new.groupby("episode_index"):
        if e not in old: continue
        go = old[e].sort_values("start"); ost, osg = go.start.to_numpy(), go.stage.to_numpy()
        for r in g.itertuples():
            f = np.arange(r.start, r.end)
            if not len(f): continue
            oi = osg[np.maximum(np.searchsorted(ost, f, side="right") - 1, 0)]
            W[r.stage] += np.bincount(oi, minlength=n_old)[:n_old]
    return W / np.maximum(W.sum(1, keepdims=True), 1)


